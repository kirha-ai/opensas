fn surfaceProbability(value: f64, critical: []const f64) Probability {
    if (value < critical[0]) return .{ .value = 0.5, .sign = .greater };
    // M9 checks the final bound before the interior intervals. Near a shape
    // boundary the fitted response surfaces can have non-monotone tail knots;
    // sorting them or interpolating first would invent a different p-value.
    if (value > critical[critical.len - 1]) return .{ .value = 0.001, .sign = .less };
    if (value == critical[critical.len - 1]) return .{ .value = 0.001 };
    return interpolate(value, critical[1..], surface_levels[1..]);
}

/// effective_n excludes all observations equal to the fitted threshold.
/// Parameter fitting still uses the full original sample.
fn exponentialEstimated(s: Statistics, effective_n: usize, e: Estimated) Result {
    // M9 emits no EDF table with fewer than five effective observations.
    if (effective_n < 5) return .{};
    const nf: f64 = @floatFromInt(effective_n);
    const inv = 1 / nf;
    const root_inv = @sqrt(inv);
    var d: [11]f64 = undefined;
    var w: [11]f64 = undefined;
    var a: [11]f64 = undefined;
    for (0..11) |i| {
        if (e.theta and e.sigma) {
            const dc = expboth_d[i];
            const wc = expboth_w[i];
            const ac = expboth_a[i];
            d[i] = @exp(dc[0] + dc[1] * root_inv + dc[2] * inv + dc[3] * inv * inv) * root_inv;
            w[i] = @exp(wc[0] + wc[1] * root_inv + wc[2] * inv);
            a[i] = @exp(ac[0] + inv * (ac[1] + inv * (ac[2] + inv * ac[3])));
        } else {
            const dc = if (e.theta) exptheta_d[i] else exp_d[i];
            const wc = if (e.theta) exptheta_w[i] else exp_w[i];
            const ac = if (e.theta) exptheta_a[i] else exp_a[i];
            d[i] = @exp(dc[0] + dc[1] * root_inv + dc[2] * inv * inv) * root_inv;
            w[i] = @exp(wc[0] + wc[1] * inv);
            a[i] = @exp(ac[0] + ac[1] * inv);
        }
    }
    return .{ .d = surfaceProbability(s.d, &d), .w2 = surfaceProbability(s.w2, &w), .a2 = surfaceProbability(s.a2, &a) };
}

